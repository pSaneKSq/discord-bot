// Общие вспомогательные функции для фронтенда дашборда.
// Подключается один раз в <head> dashboard.ejs, до всех остальных скриптов —
// поэтому escapeHtml() доступна глобально во всех js-файлах ниже без импортов.

function escapeHtml(text) {
    const map = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' };
    return String(text).replace(/[&<>"']/g, m => map[m]);
}